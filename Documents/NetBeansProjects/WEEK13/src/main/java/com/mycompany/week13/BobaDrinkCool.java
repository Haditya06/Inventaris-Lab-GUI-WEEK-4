    private void btmCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btmCalculateActionPerformed
        // TODO add your handling code here:
        try {
            jumlahMilk = Integer.parseInt(tfBobaMillk.getText().trim());
            jumlahThaiTea = Integer.parseInt(tfBobaThaiTea.getText().trim());
            jumlahRedVelvet = Integer.parseInt(tfBobaRedVelvet.getText().trim());
            jumlahOreo = Integer.parseInt(tfOreo.getText().trim());
            jumlahJelly = Integer.parseInt(tfJelly.getText().trim());
            int total = (jumlahMilk * 10000) + (jumlahThaiTea * 5000) + (jumlahRedVelvet * 10000) + (jumlahOreo * 2000) + (jumlahJelly * 2000);
            tfTotalPrice.setText(String.valueOf(total));
        } catch (NullPointerException e) {
            JOptionPane.showMessageDialog(this, "Input jumlah Harus Angka Bang!", "ERROR", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btmCalculateActionPerformed

