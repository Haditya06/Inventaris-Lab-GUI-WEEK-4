    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        // TODO add your handling code here:
        if (tfTotalPrice.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Tekan Tombol Calculate Dulu!", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            int totalPrice = Integer.parseInt(tfTotalPrice.getText());
            int totalPayment = Integer.parseInt(tfTotalPayment.getText());
            if (totalPayment < totalPrice) {
                JOptionPane.showMessageDialog(this, "Kurang Bang Uangnya", "ERROR", JOptionPane.ERROR_MESSAGE);
                return;
            }
            int kembalian = totalPayment - totalPrice;
            String pesan = "Total Harga: Rp " + totalPrice + "\n" + "Total Bayar: Rp " + totalPayment + "\n" + "Kembalian: Rp " + kembalian;
            JOptionPane.showMessageDialog(this, pesan, "Struk Belanja", JOptionPane.INFORMATION_MESSAGE);

            model.addRow(new Object[]{jumlahMilk, jumlahThaiTea, jumlahRedVelvet, jumlahOreo, jumlahJelly, totalPrice});

            tfTotalPrice.setText("");
            tfTotalPayment.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showConfirmDialog(this, "Total Payment Itu Harus Berupa Angka!", "ERROR", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProsesActionPerformed

